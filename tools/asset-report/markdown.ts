// Formats an asset report as Markdown, so it can be committed under docs/inputs/ and diffed
// between stages (the before/after numbers that Stage 6 needs for H2).

import type { Box, Report } from './glb.ts';

const MIB = 1024 * 1024;
const int = (n: number) => n.toLocaleString('en-US');
const mib = (bytes: number) => `${(bytes / MIB).toFixed(2)} MiB`;
const num = (n: number | undefined) => (n ?? 0).toFixed(3);
const size = (b: Box) =>
  [0, 1, 2].map((axis) => num((b.max[axis] ?? 0) - (b.min[axis] ?? 0))).join(' × ');
const corner = (p: number[]) => `(${p.map((v) => num(v)).join(', ')})`;

export function toMarkdown(r: Report, file: string, fileBytes: number): string {
  const lines: string[] = [];
  lines.push(`# Asset report: \`${file}\``, '');
  lines.push('Generated by `npm run report:model`. Do not edit by hand: run the script again.', '');
  lines.push('## Totals', '');
  lines.push('| Metric | Value |', '| --- | --- |');
  lines.push(`| File size | ${int(fileBytes)} B (${mib(fileBytes)}) |`);
  lines.push(`| Generator | ${r.generator} |`);
  lines.push(`| Extensions used | ${r.extensionsUsed.join(', ') || 'none'} |`);
  lines.push(`| Nodes | ${r.nodes} |`);
  lines.push(`| Draw calls (one per primitive, no instancing) | ${r.drawCalls} |`);
  lines.push(`| Triangles | ${int(r.triangles)} |`);
  lines.push(`| Vertices | ${int(r.vertices)} |`);
  lines.push(`| Geometry in GPU buffers | ${mib(r.geometryGpuBytes)} |`);
  lines.push(
    `| Images: count / bytes in file | ${r.images.length} / ${mib(r.images.reduce((n, i) => n + i.fileBytes, 0))} |`,
  );
  lines.push(`| Textures in GPU memory (RGBA8 + mipmaps, estimate) | ${mib(r.textureGpuBytes)} |`);
  lines.push(`| Scene size (x × y × z, glTF units = metres) | ${size(r.sceneBounds)} |`);
  lines.push(
    `| Scene bounds | min ${corner(r.sceneBounds.min)}, max ${corner(r.sceneBounds.max)} |`,
  );
  lines.push('');
  lines.push('## Meshes', '');
  lines.push('| Node path | Draw calls | Vertices | Triangles | Materials | Size (x × y × z, m) |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const m of r.meshNodes) {
    lines.push(
      `| ${m.path} | ${m.primitives} | ${int(m.vertices)} | ${int(m.triangles)} | ${m.materials.join(', ')} | ${size(m.bounds)} |`,
    );
  }
  lines.push('');
  lines.push('## Images', '');
  lines.push('| # | Type | Size (px) | In file | In GPU (estimate) | Used as |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const i of r.images) {
    lines.push(
      `| ${i.index} | ${i.mimeType} | ${i.width} × ${i.height} | ${mib(i.fileBytes)} | ${mib(i.gpuBytes)} | ${i.usedAs.join(', ') || 'unused'} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}
